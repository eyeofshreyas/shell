#!/usr/bin/env python3
"""Wires coding agents to the shell's AgentSessions socket (Bit mascot, AI usage card).

Usage: install-agent-hooks.py [--remove] [--list] [AGENT ...]
AGENT: claude codex gemini copilot muse cursor antigravity opencode amp (default: every one
whose config folder exists). Safe to re-run: other hooks are kept, ours are replaced.
"""
import json
import os
import shutil
import sys
from pathlib import Path

HOME = Path.home()
RELAY = Path(__file__).resolve().parent / "agent-hook.py"
MARK = "agent-hook.py"
LEGACY = "caelestia-agents.sock"  # the old nc-based Claude hooks


def cmd(agent="", event=""):
    return " ".join(["python3", f"'{RELAY}'"] + (["--agent", agent] if agent else []) + ([event] if event else []))


def ours(command):
    return isinstance(command, str) and (MARK in command or LEGACY in command)


def group_ours(group):
    inner = group.get("hooks") if isinstance(group, dict) else None
    if isinstance(inner, list):
        return any(ours(h.get("command")) for h in inner if isinstance(h, dict))
    return isinstance(group, dict) and any(ours(group.get(k)) for k in ("command", "bash", "powershell"))


def groups_install(root, events):
    """events: {name: group}. Replaces our group in each event, keeps everything else."""
    hooks = root.setdefault("hooks", {})
    for name, group in events.items():
        hooks[name] = [g for g in hooks.get(name, []) if not group_ours(g)] + [group]


def groups_remove(root):
    hooks = root.get("hooks", {})
    for name in list(hooks):
        hooks[name] = [g for g in hooks[name] if not group_ours(g)]
        if not hooks[name]:
            del hooks[name]
    if not hooks:
        root.pop("hooks", None)


def hook(command, timeout, **extra):
    return {"type": "command", "command": command, "timeout": timeout, **extra}


def claude_events():
    c = cmd()
    names = "SessionStart UserPromptSubmit PreToolUse PostToolUse PostToolUseFailure Notification Stop SessionEnd".split()
    return {n: {"hooks": [hook(c, 5)]} for n in names} | {"PermissionRequest": {"hooks": [hook(c, 120)]}}


def codex_events():
    c = cmd("codex")
    timeouts = {"SessionStart": 10, "UserPromptSubmit": 10, "PreToolUse": 10, "PermissionRequest": 120,
                "PostToolUse": 10, "Stop": 10, "SubagentStart": 10, "SubagentStop": 10, "Interrupt": 3, "SessionEnd": 3}
    return {n: {"hooks": [hook(c, t, **({"statusMessage": "Waiting for your answer in the Caelestia dashboard"} if n == "PermissionRequest" else {}))]}
            for n, t in timeouts.items()}


def gemini_events():  # timeouts in ms; AfterModel fires per chunk and would flood
    spec = {"SessionStart": ("SessionStart", 10000), "SessionEnd": ("SessionEnd", 10000), "BeforeTool": ("PreToolUse", 5000),
            "AfterTool": ("PostToolUse", 5000), "BeforeAgent": ("UserPromptSubmit", 5000), "AfterAgent": ("Stop", 5000)}
    return {n: {"matcher": "*", "hooks": [hook(cmd("gemini", ev), t)]} for n, (ev, t) in spec.items()}


def muse_events():  # timeouts in ms
    spec = {"SessionStart": 10, "UserPromptSubmit": 5, "PreToolUse": 5, "PermissionRequest": 120, "PostToolUse": 5, "Stop": 5, "SessionEnd": 3}
    return {n: {"matcher": "*", "hooks": [hook(cmd("muse", n), s * 1000)]} for n, s in spec.items()}


def cursor_events():
    names = "sessionStart sessionEnd beforeSubmitPrompt preToolUse postToolUse postToolUseFailure stop".split()
    return {n: {"command": cmd("cursor", n)} for n in names}


def copilot_entries():
    spec = {"sessionStart": 10, "userPromptSubmitted": 10, "preToolUse": 10, "permissionRequest": 120,
            "postToolUse": 10, "agentStop": 10, "sessionEnd": 3, "notification": 10}
    return {n: {"type": "command", "bash": cmd("copilot", n), "timeoutSec": t} for n, t in spec.items()}


def antigravity_block():
    h = lambda ev: {"type": "command", "command": cmd("antigravity", ev), "timeout": 10}
    return {ev: [{"matcher": "*", "hooks": [h(ev)]}] for ev in ("PreToolUse", "PostToolUse")} | {ev: [h(ev)] for ev in ("PreInvocation", "PostInvocation", "Stop")}


def write_json(path, root):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(root, indent=2) + "\n")


def read_json(path):
    if not path.exists() or not path.read_text().strip():
        return {}
    root = json.loads(path.read_text())
    if not isinstance(root, dict):
        raise ValueError(f"{path} is not a JSON object; left untouched")
    return root


GENERATED = "generated by the Caelestia shell"
OPENCODE = """// Caelestia plugin for OpenCode - %s.
import { spawn } from 'node:child_process';
const RELAY = %s;
const EVENT_MAP = { 'session.created': 'SessionStart', 'session.idle': 'Stop', 'session.error': 'StopFailure', 'session.deleted': 'SessionEnd' };
function forward(hook_event_name, payload) {
  try {
    const p = spawn('python3', [RELAY, '--agent', 'opencode'], { stdio: ['pipe', 'ignore', 'ignore'], detached: true });
    p.on('error', () => {}); p.stdin.on('error', () => {});
    p.stdin.end(JSON.stringify({ hook_event_name, ...payload }) + '\\n'); p.unref();
  } catch {}
}
export const CaelestiaPlugin = async ({ directory } = {}) => ({
  event: async ({ event }) => {
    const name = EVENT_MAP[event?.type];
    if (!name) return;
    const props = event.properties || {};
    forward(name, { session_id: props.sessionID || props.info?.id || '', cwd: directory || '' });
  },
  'tool.execute.before': async (input, output) => forward('PreToolUse', { session_id: input?.sessionID || '', cwd: directory || '', tool_name: typeof input?.tool === 'string' ? input.tool : '', tool_input: output?.args ?? null }),
  'tool.execute.after': async (input) => forward('PostToolUse', { session_id: input?.sessionID || '', cwd: directory || '', tool_name: typeof input?.tool === 'string' ? input.tool : '' }),
});
"""
AMP = """// Caelestia plugin for Amp - %s. Display only: never decides anything for Amp.
import { spawn } from 'node:child_process';
const RELAY = %s;
function forward(hook_event_name: string, fields: Record<string, unknown>): void {
  try {
    const p = spawn('python3', [RELAY, '--agent', 'amp'], { stdio: ['pipe', 'ignore', 'ignore'], detached: true });
    p.on('error', () => {}); p.stdin?.on('error', () => {});
    p.stdin?.end(JSON.stringify({ hook_event_name, ...fields }) + '\\n'); p.unref();
  } catch {}
}
export default function (amp: any): void {
  const session = (e: any) => ({ session_id: e?.thread?.id ?? '' });
  amp.on('session.start', (e: any) => { forward('SessionStart', session(e)); });
  amp.on('agent.start', (e: any) => { forward('UserPromptSubmit', { ...session(e), prompt: typeof e?.message === 'string' ? e.message : '' }); });
  amp.on('tool.result', (e: any) => { forward('PreToolUse', { ...session(e), tool_name: typeof e?.tool === 'string' ? e.tool : '', tool_input: e?.input ?? null }); });
  amp.on('agent.end', (e: any) => { forward('Stop', { ...session(e), status: e?.status ?? '' }); });
}
"""


def plugin(path, template, remove):
    if path.exists() and GENERATED not in path.read_text():
        raise ValueError(f"{path} was not written by the shell; left untouched")
    if remove:
        path.unlink(missing_ok=True)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(template % (GENERATED, json.dumps(str(RELAY))))


def json_agent(path, install_fn, remove_fn=groups_remove):
    def run(remove):
        root = read_json(path)
        (remove_fn if remove else install_fn)(root)
        if remove and not root and path.parent.name == "hooks" and path.name == "caelestia.json":
            path.unlink(missing_ok=True)
        else:
            write_json(path, root)
    return path, run


def agents():
    def antigravity_install(root):
        if "caelestia" in root and MARK not in json.dumps(root["caelestia"]):
            raise ValueError("a hook group named 'caelestia' that the shell did not write is already there")
        root["caelestia"] = antigravity_block()

    def antigravity_remove(root):
        if MARK in json.dumps(root.get("caelestia", {})):
            del root["caelestia"]

    def copilot_install(root):
        root["version"] = 1
        hooks = root.setdefault("hooks", {})
        for n, entry in copilot_entries().items():
            hooks[n] = [e for e in hooks.get(n, []) if not group_ours(e)] + [entry]

    def copilot_remove(root):
        groups_remove(root)
        if set(root) <= {"version"}:
            root.clear()

    def cursor_install(root):
        root.setdefault("version", 1)
        groups_install(root, cursor_events())

    def muse_install(root):
        if not root:
            root["schema_version"] = 1
        groups_install(root, muse_events())

    c = HOME / ".config"
    return {
        "claude": json_agent(HOME / ".claude" / "settings.json", lambda r: groups_install(r, claude_events())),
        "codex": json_agent(HOME / ".codex" / "hooks.json", lambda r: groups_install(r, codex_events())),
        "gemini": json_agent(HOME / ".gemini" / "settings.json", lambda r: groups_install(r, gemini_events())),
        "copilot": json_agent(HOME / ".copilot" / "hooks" / "caelestia.json", copilot_install, copilot_remove),
        "muse": json_agent(c / "muse" / "settings.json", muse_install),
        "cursor": json_agent(HOME / ".cursor" / "hooks.json", cursor_install),
        "antigravity": json_agent(HOME / ".gemini" / "config" / "hooks.json", antigravity_install, antigravity_remove),
        "opencode": (c / "opencode" / "plugins" / "caelestia.js", lambda rm: plugin(c / "opencode" / "plugins" / "caelestia.js", OPENCODE, rm)),
        "amp": (c / "amp" / "plugins" / "caelestia.ts", lambda rm: plugin(c / "amp" / "plugins" / "caelestia.ts", AMP, rm)),
    }


NOTES = {"codex": "Codex runs new hooks only once trusted: start Codex and review them with /hooks.",
         "claude": "Restart running Claude Code sessions (or open /hooks) to pick them up."}


def main():
    argv = sys.argv[1:]
    remove = "--remove" in argv
    table = agents()
    if "--list" in argv:
        for name, (path, _) in table.items():
            state = "installed" if path.exists() and MARK in path.read_text() else ("present" if path.parent.exists() else "absent")
            print(f"{name:12} {state:10} {path}")
        return 0
    wanted = [a for a in argv if not a.startswith("--")]
    unknown = [a for a in wanted if a not in table]
    if unknown:
        print(f"unknown agent(s): {' '.join(unknown)}; choose from: {' '.join(table)}", file=sys.stderr)
        return 2
    if not wanted:  # every agent whose config folder already exists (claude always)
        wanted = [n for n, (p, _) in table.items() if n == "claude" or p.parent.exists() or p.parent.parent.exists()]
    status = 0
    for name in wanted:
        path, run = table[name]
        try:
            backup = path.with_name(path.name + ".bak-agents")
            if path.exists() and not backup.exists() and MARK not in path.read_text() and GENERATED not in path.read_text():
                shutil.copy2(path, backup)
            run(remove)
            print(f"{'removed from' if remove else 'installed into'} {name}: {path}")
            if not remove and name in NOTES:
                print(f"  {NOTES[name]}")
        except (ValueError, OSError) as e:
            print(f"{name}: {e}", file=sys.stderr)
            status = 1
    return status


if __name__ == "__main__":
    sys.exit(main())
